import { chromium } from 'file:///C:/Users/itang/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { inspectGIF } from '../test-resources/crop-benchmark/src/gif-meta.js';
const edge = process.argv.includes('--edge');
const blue = process.argv.includes('--blue');
const outputFolder = blue ? (edge ? './screenshots/blue/edge/' : './screenshots/blue/') : (edge ? './screenshots/edge/' : './screenshots/');
const folder = fileURLToPath(new URL(outputFolder, import.meta.url));
await mkdir(folder, { recursive: true });
const browser = await chromium.launch({ channel: edge ? 'msedge' : 'chrome', headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:4186/', { waitUntil: 'networkidle' });
  await page.waitForFunction(() => window.designPreview?.meta?.width === 800);
  if (blue) {
    const palette = await page.evaluate(() => ({ page: getComputedStyle(document.body).backgroundColor, stage: getComputedStyle(document.getElementById('stage')).backgroundColor, button: getComputedStyle(document.getElementById('crop')).backgroundColor, choose: getComputedStyle(document.getElementById('choose')).backgroundColor, selected: getComputedStyle(document.getElementById('free')).backgroundColor }));
    assert.deepEqual(palette, { page: 'rgb(255, 255, 255)', stage: 'rgb(245, 246, 248)', button: 'rgb(37, 99, 235)', choose: 'rgb(37, 99, 235)', selected: 'rgb(239, 246, 255)' });
    assert.equal(await page.locator('h1').innerText(), 'Crop animated GIF');
    await page.locator('#crop').hover();
    await page.waitForTimeout(220);
    assert.equal(await page.locator('#crop').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(29, 78, 216)');
    await page.mouse.move(0, 0);
    await page.waitForTimeout(220);
  }
  assert.deepEqual(await page.evaluate(() => window.designPreview.selection), { x: 0, y: 0, width: 800, height: 500 });
  await page.screenshot({ path: folder+'desktop-default.png' });
  await page.locator('#width').fill('560'); await page.locator('#height').fill('360');
  const scale = await page.locator('#image-wrap').evaluate(el => el.getBoundingClientRect().width/800);
  const box = await page.locator('#selection').boundingBox();
  await page.mouse.move(box.x+box.width/2, box.y+box.height/2); await page.mouse.down();
  await page.mouse.move(box.x+box.width/2+120*scale, box.y+box.height/2+70*scale, { steps: 8 }); await page.mouse.up();
  const selected = await page.evaluate(() => window.designPreview.selection);
  assert.deepEqual(selected, { x: 120, y: 70, width: 560, height: 360 });
  await page.screenshot({ path: folder+'desktop-editor.png' });
  await page.locator('#crop').click();
  await page.waitForFunction(() => !document.getElementById('result-filled').hidden, { timeout: 65000 });
  await page.waitForFunction(() => !window.designPreview.busy);
  const downloadEvent = page.waitForEvent('download'); await page.locator('#download').click();
  const download = await downloadEvent; await download.saveAs(folder+'cropped-demo.gif');
  const bytes = await readFile(folder+'cropped-demo.gif');
  const output = inspectGIF(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset+bytes.byteLength));
  assert.equal(output.width, 560); assert.equal(output.height, 360); assert.equal(output.frames.length, 16);
  assert.ok(output.frames.every(f => f.delay === 100)); assert.equal(output.loop, 0);
  await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }));
  await page.screenshot({ path: folder+'desktop-result.png', fullPage: true });
  await page.locator('#square').click();
  const square = await page.evaluate(() => window.designPreview.selection); assert.equal(square.width, square.height);
  assert.equal(await page.locator('#result-filled').isHidden(), true);
  const squareHandle = await page.locator('.handle.se').boundingBox();
  await page.mouse.move(squareHandle.x+5, squareHandle.y+5); await page.mouse.down();
  await page.mouse.move(squareHandle.x+5-40*scale, squareHandle.y+5-60*scale, { steps: 5 }); await page.mouse.up();
  const resizedSquare = await page.evaluate(() => window.designPreview.selection);
  assert.equal(resizedSquare.width, square.width-60); assert.equal(resizedSquare.width, resizedSquare.height);
  await page.locator('#width').fill('0'); assert.equal(await page.locator('#crop').isDisabled(), true);
  await page.locator('#width').fill('300'); assert.equal(await page.locator('#height').inputValue(), '300');
  await page.locator('#reset').click();
  assert.deepEqual(await page.evaluate(() => window.designPreview.selection), { x: 0, y: 0, width: 800, height: 500 });
  const freeHandle = await page.locator('.handle.se').boundingBox();
  await page.mouse.move(freeHandle.x+5, freeHandle.y+5); await page.mouse.down();
  await page.mouse.move(freeHandle.x+5-80*scale, freeHandle.y+5-50*scale, { steps: 5 }); await page.mouse.up();
  assert.deepEqual(await page.evaluate(() => window.designPreview.selection), { x: 0, y: 0, width: 720, height: 450 });
  await page.locator('#selection').press('Shift+ArrowRight');
  assert.equal((await page.evaluate(() => window.designPreview.selection)).x, 10);
  await page.locator('#reset').click();
  await page.locator('#file').setInputFiles(fileURLToPath(new URL('../test-resources/codec-corpus/invalid/empty.gif', import.meta.url)));
  await page.waitForFunction(() => document.getElementById('status').classList.contains('error'));
  await page.locator('#file').setInputFiles(fileURLToPath(new URL('./art/coastal-loop.gif', import.meta.url)));
  await page.waitForFunction(() => !document.getElementById('status').classList.contains('error') && !window.designPreview.busy);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: folder+'narrow-layout.png', fullPage: true });
  assert.deepEqual(errors, []);
  const report = { browser: browser.version(), defaultFullImage: true, numericDimensions: true, pointerMove: selected, pointerResize: true, squarePointerResize: true, keyboardMove: true, squareMode: true, invalidDimensionsBlocked: true, resultInvalidation: true, invalidFileRecovery: true, actualGifDownload: { width: output.width, height: output.height, frames: output.frames.length, allFrameDelaysMs: 100, loop: 0, bytes: bytes.length }, narrowLayoutNoOverflow: true, note: 'UI draft smoke check; not the full product/browser/capacity acceptance', pageErrors: errors };
  if (blue) report.palette = { page: '#FFFFFF', editor: '#F5F6F8', primary: '#2563EB', hover: '#1D4ED8', selected: '#EFF6FF' };
  await writeFile(folder+'checks.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally { await browser.close(); }
